# RAMAN Studio Analysis Engine
# Integrates multiple open-source electrochemistry analysis packages:
#
# 1. Electrochem-Suite (VidyuthLabs) — Auto-detect, publication plots, AI reports
# 2. impedance.py (ECS HackWeek) — EIS circuit fitting, validation, preprocessing
# 3. pyDRTtools (Ciucci Lab) — DRT computation via Tikhonov regularization
# 4. MADAP (Rahmanian) — Modular electrochemistry analysis platform
#
# References:
#   - impedance.py: Murbach et al., JOSS 2020, doi:10.21105/joss.02349
#   - pyDRTtools: Wan et al., Electrochimica Acta 2015
#   - MADAP: Rahmanian et al., JOSS 2024
#   - Open-EChemNet: Zhang et al., Nature Communications 2024
